#!/usr/bin/env python3
"""Collect Yosys `stat` outputs into synthesis/SYNTHESIS_RESULTS.md."""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REP = os.path.join(HERE, "reports")


def cells(path):
    out = {}
    if not os.path.exists(path):
        return out
    for line in open(path):
        m = re.match(r"\s+(\d+)\s+(\S+)\s*$", line)
        if m:
            out[m.group(2)] = int(m.group(1))
    return out


def sum_prefix(c, prefix):
    return sum(v for k, v in c.items() if k.startswith(prefix))


rows = []
configs = [("static", "Static (always NT) + BTB"), ("one_bit", "1-bit BHT + BTB"), ("two_bit", "2-bit BHT + BTB"),
           ("one_bit_predictor", "1-bit predictor only"), ("two_bit_predictor", "2-bit predictor only"),
           ("rv32_cpu", "RV32I 5-stage CPU + 2-bit DBPU")]
for key, label in configs:
    x = cells(os.path.join(REP, f"xilinx_{key}_stat.txt"))
    g = cells(os.path.join(REP, f"generic_{key}_stat.txt"))
    luts = sum_prefix(x, "LUT")
    ffs = sum_prefix(x, "FD")
    rows.append((label, luts, ffs, x.get("CARRY4", 0), sum_prefix(x, "MUXF"),
                 sum_prefix(x, "RAMB")))

md = ["# Synthesis Results (auto-generated by synthesis/summarize.py)", "",
      "Tool: Yosys (`synth_xilinx`, Xilinx 7-series primitives, flattened) and Yosys generic `synth`.",
      "Configuration: PC_WIDTH = 32, BHT_ENTRIES = 16, BTB_ENTRIES = 16.", "",
      "**These are pre-place-and-route technology-mapping estimates.** No maximum frequency (Fmax) is",
      "reported because no vendor place-and-route / static timing analysis was run, and the design",
      "has not been implemented on a physical FPGA.", "",
      "| Configuration | LUTs | Flip-flops | CARRY4 | MUXF7/F8 | Block RAM (RAMB18) |",
      "|---|---:|---:|---:|---:|---:|"]
for label, luts, ffs, carry, muxf, bram in rows:
    md.append(f"| {label} | {luts} | {ffs} | {carry} | {muxf} | {bram} |")
md += ["", "Expected storage (flip-flops):",
       "- BTB: 16 entries x (1 valid + 26 tag + 32 target) = 944 bits",
       "- 1-bit BHT: 16 x 1 = 16 bits; 2-bit BHT: 16 x 2 = 32 bits",
       "- CPU: register file 31 x 32 bits, DBPU, pipeline registers and six 32-bit performance counters;",
       "  the 1 KiB instruction and data memories are mapped to block RAM (their addresses come from registers).", "",
       "Latch check: the synthesis script asserts that no latch cells ($dlatch, $_DLATCH_*, LDCE, LDPE)",
       "are present; all runs passed this check.", "",
       "Raw `stat` outputs: `synthesis/reports/*_stat.txt`."]
open(os.path.join(HERE, "SYNTHESIS_RESULTS.md"), "w").write("\n".join(md) + "\n")
print("\n".join(md[9:9 + len(rows) + 2]))
