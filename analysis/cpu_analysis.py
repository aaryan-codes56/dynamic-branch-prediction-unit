#!/usr/bin/env python3
"""
cpu_analysis.py - Phase II: measured CPI of the 5-stage RV32I pipeline.

Input : analysis/results/cpu_results.csv  (written by testbench/tb_rv32_pipeline.v)
Output: analysis/results/cpu_summary.md, analysis/results/cpu_summary.json,
        analysis/plots/cpu_cpi_comparison.{png,pdf}

All numbers come from the hardware performance counters of the simulated CPU:
  CPI = cycles / instructions retired
  direction accuracy = 1 - dir_mispredicts / branches
  speed-up = cycles(static) / cycles(predictor)
The script also re-checks the cycle accounting identity
  cycles = instret + 4 + 2*flushes + stalls
"""
import csv
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(ROOT, "analysis", "results")
PLOTS = os.path.join(ROOT, "analysis", "plots")
PRED = [("static", "Always not taken"), ("one_bit", "1-bit dynamic"), ("two_bit", "2-bit dynamic")]
COLORS = {"static": "#2a78d6", "one_bit": "#eb6834", "two_bit": "#1baf7a"}


def main():
    path = os.path.join(RES, "cpu_results.csv")
    rows = list(csv.DictReader(open(path)))
    data, bad = {}, 0
    for r in rows:
        c = {k: int(r[k]) for k in ("cycles", "instret", "branches", "flushes", "dir_mispredicts", "stalls")}
        if c["cycles"] != c["instret"] + 4 + 2 * c["flushes"] + c["stalls"]:
            bad += 1
            print(f"cycle identity violated: {r}")
        c["cpi"] = c["cycles"] / c["instret"]
        c["accuracy_pct"] = 100.0 * (1 - c["dir_mispredicts"] / c["branches"]) if c["branches"] else 100.0
        data.setdefault(r["program"], {})[r["predictor"]] = c
    programs = sorted(data)
    for p in programs:
        base = data[p]["static"]["cycles"]
        for k, _ in PRED:
            data[p][k]["speedup"] = base / data[p][k]["cycles"]

    totals = {k: {f: sum(data[p][k][f] for p in programs) for f in ("cycles", "instret", "flushes", "stalls", "branches")}
              for k, _ in PRED}
    for k, _ in PRED:
        totals[k]["cpi"] = totals[k]["cycles"] / totals[k]["instret"]
        totals[k]["speedup"] = totals["static"]["cycles"] / totals[k]["cycles"]

    md = ["# CPU Results: 5-stage RV32I pipeline with the DBPU (auto-generated)", "",
          "Generated by `analysis/cpu_analysis.py` from `cpu_results.csv` (hardware performance counters of the "
          "simulated CPU, `make cpu`). Every run was checked against the reference ISS (registers, memory, "
          "instruction count). Branches resolve in EX: 2-cycle misprediction penalty; load-use: 1-cycle stall.", "",
          "| Program | Predictor | Instr. | Cycles | CPI | Branches | Branch fraction (%) | Flushes | Flush penalty (cycles) | Direction accuracy (%) | Load-use stalls | Speed-up vs static |",
          "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|"]
    for p in programs:
        for k, lab in PRED:
            c = data[p][k]
            branch_frac = 100.0 * c['branches'] / c['instret'] if c['instret'] else 0.0
            flush_penalty = 2 * c['flushes']
            md.append(f"| {p} | {lab} | {c['instret']} | {c['cycles']} | {c['cpi']:.3f} | {c['branches']} | "
                      f"{branch_frac:.1f} | {c['flushes']} | {flush_penalty} | {c['accuracy_pct']:.2f} | {c['stalls']} | {c['speedup']:.3f} |")
    md += ["", "**All programs combined**", "",
           "| Predictor | Instr. | Cycles | CPI | Flushes | Speed-up vs static |", "|---|---:|---:|---:|---:|---:|"]
    for k, lab in PRED:
        t = totals[k]
        md.append(f"| {lab} | {t['instret']} | {t['cycles']} | {t['cpi']:.3f} | {t['flushes']} | {t['speedup']:.3f} |")
    os.makedirs(RES, exist_ok=True)
    open(os.path.join(RES, "cpu_summary.md"), "w").write("\n".join(md) + "\n")
    json.dump({"programs": data, "totals": totals}, open(os.path.join(RES, "cpu_summary.json"), "w"), indent=2)

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
        plt.rcParams.update({"font.size": 9, "axes.spines.top": False, "axes.spines.right": False,
                             "axes.grid": True, "grid.color": "#e4e3df", "grid.linewidth": 0.6,
                             "axes.axisbelow": True, "axes.edgecolor": "#52514e",
                             "xtick.color": "#52514e", "ytick.color": "#52514e"})
        fig, ax = plt.subplots(figsize=(7.0, 2.9))
        w = 0.26
        for j, (k, lab) in enumerate(PRED):
            xs = [i + (j - 1) * (w + 0.01) for i in range(len(programs))]
            vals = [data[p][k]["cpi"] for p in programs]
            bars = ax.bar(xs, vals, w, color=COLORS[k], label=lab, edgecolor="#ffffff", linewidth=1.0)
            for b, v in zip(bars, vals):
                ax.text(b.get_x() + b.get_width() / 2, v, f"{v:.2f}", ha="center", va="bottom",
                        fontsize=6, color="#52514e")
        ax.set_xticks(range(len(programs)))
        ax.set_xticklabels([p.replace("_", "\n", 1) for p in programs])
        ax.set_ylabel("Measured CPI")
        ax.set_ylim(1.0, max(data[p]["static"]["cpi"] for p in programs) * 1.12)
        ax.grid(axis="x", visible=False)
        ax.legend(frameon=False, ncol=3, loc="upper center", bbox_to_anchor=(0.5, 1.18))
        fig.tight_layout()
        os.makedirs(PLOTS, exist_ok=True)
        for ext in ("png", "pdf"):
            fig.savefig(os.path.join(PLOTS, f"cpu_cpi_comparison.{ext}"), dpi=200,
                        metadata={"CreationDate": None} if ext == "pdf" else None)
        plt.close(fig)
    except ImportError:
        print("matplotlib not installed - skipping plot")

    print(open(os.path.join(RES, "cpu_summary.md")).read())
    if bad:
        print(f"RESULT: FAIL - {bad} runs violate the cycle identity")
        sys.exit(1)
    print("RESULT: PASS - cycle accounting identity holds for every run")


if __name__ == "__main__":
    main()
